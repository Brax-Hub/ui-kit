#!/usr/bin/env node
// `tinbase gen types typescript`, in process: boots a throwaway backend (PGlite in memory) on the app's migrations and
// writes the Supabase-shaped Database type to src/server/db/database.types.ts. Commit the output; never edit it.
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { createBackend, generateTypes } from 'tinbase'
import { loadSupabaseProject } from 'tinbase/node'

const root = process.cwd()
const out = process.argv[2] ?? join(root, 'src', 'server', 'db', 'database.types.ts')
const project = await loadSupabaseProject(root, { enabled: false })
const backend = await createBackend({ migrations: project.migrations, authEnabled: false, jwtSecret: 'gen-types-throwaway-secret-0123456789abcdef' })
try {
  if (backend.db.migrationFailure) throw new Error(`migration ${backend.db.migrationFailure.name} failed: ${backend.db.migrationFailure.error}`)
  const text = await generateTypes(backend.db, 'public')
  writeFileSync(out, `// Generated by tooling/gen-types.mjs (tinbase gen types typescript). Do not edit.\n${text}`)
  console.log(`wrote ${out}`)
} finally {
  await backend.close()
}
